/* ================= v160: عنوان التصريح ونصه بحسب نوع النشاط (طلب يوسف: «دورة علمية» ليست «إلقاء درس») ================= */
/* النوع من التصريح نفسه (data.kind للتصاريح الجديدة)، وإلا من نشاطه المرتبط، وإلا «درس ديني». يُستعمل في الورقة وPDF والواتساب والمشاركة والإصدار الجماعي. */
const PERMIT_KINDS = {
  "درس ديني":     { title:"تصريح إلقاء درس",   verb:"إلقاء درس",        noun:"الدرس" },
  "دورة علمية":   { title:"تصريح دورة علمية",  verb:"إقامة دورة علمية", noun:"الدورة" },
  "محاضرة دينية": { title:"تصريح محاضرة",      verb:"إلقاء محاضرة",     noun:"المحاضرة" },
};
function permitKind(p){
  const type = p?.data?.kind || (p?.act_id && S.byId?.get(p.act_id)?.type) || "درس ديني";
  return { type, ...(PERMIT_KINDS[type] || { title:`تصريح ${type}`, verb:`إقامة ${type}`, noun:"النشاط" }) };
}
